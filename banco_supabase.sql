-- Script para executar no Supabase: Dashboard > SQL Editor > New query.
-- O Supabase ja fornece o banco de dados; nao use CREATE DATABASE ou USE.

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS produtos (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    categoria VARCHAR(30) NOT NULL,
    preco NUMERIC(8,2) NOT NULL CHECK (preco >= 0)
);

CREATE TABLE IF NOT EXISTS comandas (
    id_comanda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(100) NOT NULL,
    mesa INTEGER NOT NULL CHECK (mesa > 0),
    status VARCHAR(20) NOT NULL,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    data_abertura TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS itens_comanda (
    id_item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comanda INTEGER NOT NULL REFERENCES comandas(id_comanda) ON DELETE CASCADE,
    id_produto INTEGER NOT NULL REFERENCES produtos(id_produto),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(8,2) NOT NULL CHECK (preco_unitario >= 0)
);

